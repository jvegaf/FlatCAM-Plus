"""The Linux packages are generated from files in this directory, so the files have to be right.

`nfpm` turns ``packaging/linux/nfpm.yaml`` into both a deb and an rpm, and the metadata is only as
good as the paths it names. These guards read the same files nfpm reads: a renamed asset, a
relative ``Exec`` or an unreadable desktop file fails here instead of in a released package.
"""

import os
import re
import subprocess
import xml.etree.ElementTree as ElementTree

import pytest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LINUX_PACKAGING = os.path.join(REPO_ROOT, "packaging", "linux")
NFPM_CONFIG = os.path.join(LINUX_PACKAGING, "nfpm.yaml")
DESKTOP_FILE = os.path.join(LINUX_PACKAGING, "flatcam-plus.desktop")
METAINFO_FILE = os.path.join(LINUX_PACKAGING, "flatcam-plus.metainfo.xml")
WRAPPER = os.path.join(LINUX_PACKAGING, "flatcam-plus.sh")


def read(path):
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def contents_sources():
    return re.findall(r"^  - src: (.+)$", read(NFPM_CONFIG), re.MULTILINE)


def test_every_checked_in_file_the_package_names_exists():
    """dist/ is generated by the build, so only the tracked sources can be checked here."""
    sources = contents_sources()

    assert sources
    checked_in = [source.strip() for source in sources if not source.strip().startswith("dist/")]
    generated = [source.strip() for source in sources if source.strip().startswith("dist/")]
    assert checked_in and generated, sources
    for relative in checked_in:
        assert os.path.exists(os.path.join(REPO_ROOT, relative)), relative


def test_the_package_takes_its_version_from_the_manifest():
    config = read(NFPM_CONFIG)

    assert "version: ${VERSION}" in config
    assert not re.search(r"^version: \d", config, re.MULTILINE)


def test_the_license_matches_the_repository():
    first_line = read(os.path.join(REPO_ROOT, "LICENSE")).splitlines()[0]

    assert first_line == "License Scope Notice"
    assert re.search(r"^license: MIT$", read(NFPM_CONFIG), re.MULTILINE)


def test_the_desktop_entry_is_written_for_a_system_install():
    desktop = read(DESKTOP_FILE)
    fields = dict(
        line.split("=", 1) for line in desktop.splitlines() if "=" in line and not line.startswith("[")
    )

    assert fields["Type"] == "Application"
    assert fields["Exec"].split()[0] == "flatcam-plus", "a system install has no relative payload"
    assert not fields["Exec"].startswith("./")
    assert not fields["Icon"].startswith("./")
    assert fields["Icon"] == "flatcam-plus"
    assert "Categories" in fields


def test_the_package_forces_the_desktop_data_mode():
    config = read(NFPM_CONFIG)

    for dst in (
        "/usr/share/applications/flatcam-plus.desktop",
        "/usr/share/metainfo/flatcam-plus.metainfo.xml",
    ):
        block = config.split("dst: " + dst, 1)[1].split("- src:", 1)[0]
        assert "mode: 0644" in block, dst


def test_the_metainfo_answers_what_appstream_requires():
    component = ElementTree.parse(METAINFO_FILE).getroot()

    assert component.tag == "component"
    assert component.get("type") == "desktop-application"
    for child in ("id", "name", "summary", "metadata_license", "project_license"):
        assert component.find(child) is not None, child
    assert component.find("project_license").text == "MIT"
    launchable = component.find("launchable")
    assert launchable.get("type") == "desktop-id"
    assert launchable.text == os.path.basename(DESKTOP_FILE)
    releases = component.find("releases")
    assert releases is not None and releases.find("release") is not None


def test_the_wrapper_runs_the_payload_from_opt(tmp_path):
    payload_dir = tmp_path / "payload"
    payload_dir.mkdir()
    payload = payload_dir / "FlatCAM-Plus"
    payload.write_text("#!/bin/sh\necho payload ran with: $*\n", encoding="utf-8")
    payload.chmod(0o755)

    finished = subprocess.run(
        [WRAPPER, "--version"],
        capture_output=True,
        text=True,
        env=dict(os.environ, FLATCAM_PLUS_HOME=str(payload_dir)),
        timeout=120,
    )

    assert finished.returncode == 0, finished.stderr
    assert "payload ran with: --version" in finished.stdout


def test_the_wrapper_explains_a_missing_payload(tmp_path):
    finished = subprocess.run(
        [WRAPPER],
        capture_output=True,
        text=True,
        env=dict(os.environ, FLATCAM_PLUS_HOME=str(tmp_path / "absent")),
        timeout=120,
    )

    assert finished.returncode != 0
    assert "no executable payload" in finished.stderr


GLIBC_CHECKER = os.path.join(LINUX_PACKAGING, "check_glibc_floor.py")


def load_glibc_checker():
    import importlib.util

    spec = importlib.util.spec_from_file_location("check_glibc_floor", GLIBC_CHECKER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_the_glibc_checker_reads_the_highest_reference():
    checker = load_glibc_checker()

    symbols = (
        "0000000000000000 DF *UND* 0000000000000000 GLIBC_2.17 memcpy\n"
        "0000000000000000 DF *UND* 0000000000000000 GLIBC_2.28 pow\n"
        "0000000000000000 DF *UND* 0000000000000000 GLIBC_2.9 strfry\n"
    )

    assert checker.max_glibc_version(symbols) == "2.28"
    assert checker.max_glibc_version("no versions here") is None


@pytest.mark.parametrize(
    "symbols, expected_floor, expected_status",
    [
        ("GLIBC_2.17 memcpy\nGLIBC_2.28 pow\n", "2.28", 0),
        ("GLIBC_2.17 memcpy\nGLIBC_2.28 pow\n", "2.31", 0),
        ("GLIBC_2.17 memcpy\nGLIBC_2.34 pthread\n", "2.28", 1),
    ],
)
def test_the_glibc_checker_fails_only_when_the_floor_is_exceeded(
    tmp_path, monkeypatch, symbols, expected_floor, expected_status
):
    checker = load_glibc_checker()
    (tmp_path / "libwhatever.so.1").write_bytes(b"\x7fELF")
    monkeypatch.setattr(checker, "symbols_of", lambda path: symbols)

    assert checker.main(["check", str(tmp_path), expected_floor]) == expected_status


def test_the_glibc_checker_refuses_an_empty_bundle(tmp_path, capsys):
    checker = load_glibc_checker()

    assert checker.main(["check", str(tmp_path), "2.28"]) == 1
    assert "no shared objects" in capsys.readouterr().err


